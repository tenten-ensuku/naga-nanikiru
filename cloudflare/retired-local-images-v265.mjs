const appOrigin='https://minkiru.naga-study.workers.dev';
const pagesOrigin='https://tenten-ensuku.github.io';

export function isRetiredLocalImage(value,paths=retiredPaths){
  if(typeof value!=='string'||value.length>4096||(!/\.(?:png|jpe?g|webp|gif)(?:[?#]|$)/i.test(value)&&!value.includes('%')))return false;
  let url;try{url=new URL(value,appOrigin+'/');}catch{return false;}
  if(url.origin!==appOrigin&&url.origin!==pagesOrigin)return false;
  // Static asset URLs are resolved by the browser, not the R2 path parser.
  // Decode ordinary filename punctuation too (for example q158%2Ewebp).
  let decoded=url.pathname;
  for(let round=0;round<8;round++){let next;try{next=decodeURIComponent(decoded);}catch{return false;}if(next===decoded)break;decoded=next;}
  let resolved;try{resolved=new URL(decoded,url.origin);}catch{return false;}
  if(resolved.origin!==url.origin)return false;
  let asset=resolved.pathname.replace(/^\//,'');
  if(asset.startsWith('naga-nanikiru/'))asset=asset.slice('naga-nanikiru/'.length);
  for(let round=0;round<8;round++){const next=normalizeAssetPath(asset);if(!next)return false;if(next===asset)break;asset=next;}
  return paths.has(asset);
}
